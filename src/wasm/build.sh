#!/bin/bash
# Builds the wasm kernels of RenderCore: for each kernel K, K.c -> K.wasm.js,
# the generated module that exports the bytes as base64, with the compiler,
# the flags and the date of the build in its header, so the kernel loads
# through the same import path as every other RenderCore file and a bundle
# carries it without an asset. The module is committed; the binary is written
# to a temporary directory and is not. Run this after changing a kernel.
#
# Needs clang with the wasm32 target and wasm-ld (Fedora: clang, lld).

set -e
cd "$(dirname "$0")"

CLANG=${CLANG:-clang}
# -nostdlib, no entry: a freestanding module of exported functions.
# --import-memory: the memory is the arena's, imported as env.memory.
# __heap_base is exported so the arena can check that the module's stack
# stays below its first allocation.
CFLAGS="--target=wasm32 -O2 -msimd128 -ffreestanding -nostdlib"
LDFLAGS="-Wl,--no-entry -Wl,--import-memory -Wl,--export=__heap_base"
VERSION=$($CLANG --version | head -n 1)
DATE=$(date -u +%F)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

for k in zlines_walk; do
    $CLANG $CFLAGS $LDFLAGS -o "$TMP/$k.wasm" $k.c

    node - "$k" "$TMP/$k.wasm" "$VERSION" "$CFLAGS $LDFLAGS" "$DATE" <<'NODE'
const fs = require("fs");
const [k, path, version, flags, date] = process.argv.slice(2);
const bytes = fs.readFileSync(path);
// Section 11 is the data section. Kernels share the bottom of the memory for
// their stacks, which never nest; static data there would be overwritten by
// the next kernel's instantiation.
for (let o = 8; o < bytes.length;) {
    const id = bytes[o++];
    let size = 0, shift = 0, b;
    do { b = bytes[o++]; size |= (b & 0x7f) << shift; shift += 7; } while (b & 0x80);
    if (id === 11) { console.error(k + ".wasm has a data section; kernels must not have static data"); process.exit(1); }
    o += size;
}
const b64 = bytes.toString("base64");
const lines = [];
for (let i = 0; i < b64.length; i += 100) lines.push('    "' + b64.slice(i, i + 100) + '"');
const out =
`// GENERATED by src/wasm/build.sh from src/wasm/${k}.c; do not edit.
// The bytes of ${k}.wasm (${bytes.length} bytes) as base64, built ${date} by
// ${version}
// with ${flags}.
export const ${k.toUpperCase()}_WASM =
${lines.join(" +\n")};
`;
fs.writeFileSync(k + ".wasm.js", out);
console.log(k + ".wasm.js: " + bytes.length + " bytes of kernel, " + version + ", " + date);
NODE
done
